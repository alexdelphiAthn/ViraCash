-- Listas de regalos (nacimiento, bautizo, comunión...).
-- Los titulares eligen artículos y cada invitado regala el que quiera,
-- en caja o en PrestaShop. Las cantidades regaladas no se guardan en la
-- línea: se suman desde fza_listas_regalos_regalos (VI_LRG_LINEAS_ESTADO).
-- VERSION_LRG crece con cada cambio visible en la web; la publicación en
-- cada tienda PrestaShop guarda la versión enviada (LRGPUB).
SET @DDL_LRG = IF(EXISTS(SELECT 1 FROM INFORMATION_SCHEMA.TABLES
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'fza_listas_regalos'),
  'SELECT ''fza_listas_regalos ya existe; se omite'' AS info',
  'CREATE TABLE fza_listas_regalos (
  CODIGO_LRG varchar(20) NOT NULL,
  CODIGO_EMP_LRG varchar(10) NOT NULL,
  CODIGO_ALM_LRG varchar(10) NOT NULL,
  CODIGO_CLI_LRG varchar(20) NULL DEFAULT NULL,
  TIPO_LRG varchar(15) NOT NULL DEFAULT ''NACIMIENTO'',
  ESTADO_LRG varchar(10) NOT NULL DEFAULT ''ABIERTA'',
  CLAVE_PUBLICA_LRG varchar(12) NOT NULL,
  TITULO_LRG varchar(120) NOT NULL,
  NOMBRE_HOMENAJEADO_LRG varchar(100) NULL DEFAULT NULL,
  NOMBRE_TITULARES_LRG varchar(150) NOT NULL,
  EMAIL_TITULARES_LRG varchar(150) NULL DEFAULT NULL,
  MOVIL_TITULARES_LRG varchar(30) NULL DEFAULT NULL,
  MENSAJE_LRG text NULL,
  FECHA_EVENTO_LRG date NULL DEFAULT NULL,
  FECHA_CADUCIDAD_LRG date NULL DEFAULT NULL,
  TIPO_ENTREGA_LRG varchar(10) NOT NULL DEFAULT ''TIENDA'',
  ESPUBLICA_WEB_LRG varchar(1) NOT NULL DEFAULT ''S'',
  ESBUSCABLE_LRG varchar(1) NOT NULL DEFAULT ''S'',
  PORCENTAJE_BONIFICACION_LRG decimal(5,2) NOT NULL DEFAULT 0,
  PORCENTAJE_DESCUENTO_CIERRE_LRG decimal(5,2) NOT NULL DEFAULT 0,
  VERSION_LRG int NOT NULL DEFAULT 1,
  FECHA_CIERRE_LRG date NULL DEFAULT NULL,
  TOTAL_REGALADO_LRG decimal(19,6) NULL DEFAULT NULL,
  IMPORTE_BONIFICACION_LRG decimal(19,6) NULL DEFAULT NULL,
  CODIGO_VL_LRG varchar(50) NULL DEFAULT NULL,
  OBSERVACIONES_LRG varchar(500) NULL DEFAULT NULL,
  INSTANTE_ALTA datetime NOT NULL,
  USUARIO_ALTA varchar(100) NOT NULL,
  INSTANTE_MODIF datetime NULL DEFAULT NULL,
  USUARIO_MODIF varchar(100) NULL DEFAULT NULL,
  PRIMARY KEY (CODIGO_LRG),
  UNIQUE KEY UQ_LRG_CLAVE_PUBLICA (CLAVE_PUBLICA_LRG),
  KEY IDX_LRG_EMP_ESTADO (CODIGO_EMP_LRG, ESTADO_LRG),
  KEY IDX_LRG_CLI (CODIGO_CLI_LRG),
  KEY IDX_LRG_TITULARES (NOMBRE_TITULARES_LRG),
  KEY IDX_LRG_HOMENAJEADO (NOMBRE_HOMENAJEADO_LRG)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_spanish_ci');
PREPARE STMT_LRG FROM @DDL_LRG;
EXECUTE STMT_LRG;
DEALLOCATE PREPARE STMT_LRG;
